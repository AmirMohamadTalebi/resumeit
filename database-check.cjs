const assert = require('node:assert/strict');
const { mkdtempSync, mkdirSync } = require('node:fs');
const path = require('node:path');
const { openDatabase } = require('./database.cjs');
mkdirSync(path.join(__dirname, 'artifacts'), { recursive: true });
const filename = path.join(mkdtempSync(path.join(__dirname, 'artifacts', 'db-check-')), 'test.sqlite');
let database = openDatabase(filename);
const first = database.userAfterVerifiedPhone('09120000001');
const second = database.userAfterVerifiedPhone('09120000002');
assert.equal(database.userAfterVerifiedPhone('09120000001'), first);
const profile = { name: "O'Reilly", role: 'Developer', bio: '', links: [{ name: 'Site', url: 'https://example.com/' }] };
database.saveProfile(first, profile);
assert.equal(database.getProfile(second).links.length, 0);
assert.throws(() => database.saveProfile(first, { ...profile, name: '  ' }));
assert.throws(() => database.saveProfile(first, { ...profile, links: [{ name: 'Unsafe', url: 'javascript:alert(1)' }] }));
assert.throws(() => database.saveProfile('unknown', profile));
assert.equal(database.getProfile(first).name, profile.name);
database.close();
database = openDatabase(filename);
assert.deepEqual(JSON.parse(JSON.stringify(database.getProfile(first))), profile);
database.close();
console.log('PASS: database persistence, separate user records, invalid input rejected without overwriting saved data.');
