const assert = require('node:assert/strict');
const { createOtpService } = require('./otp.cjs');
(async () => {
  let time = 0, sent;
  const service = createOtpService({ now: () => time, send: async (phone, code) => { sent = { phone, code }; } });
  await assert.rejects(service.request('invalid'));
  const first = await service.request('09120000001');
  assert.match(sent.code, /^\d{6}$/);
  assert.equal(first.code, undefined);
  await assert.rejects(service.request(sent.phone), /wait/);
  assert.throws(() => service.verify(first.challengeId, 'wrong'));
  assert.deepEqual(service.verify(first.challengeId, sent.code), { phone: sent.phone });
  assert.throws(() => service.verify(first.challengeId, sent.code));
  time += 60000;
  const second = await service.request(sent.phone);
  time += 120000;
  assert.throws(() => service.verify(second.challengeId, sent.code));
  const third = await service.request(sent.phone);
  for (let i = 0; i < 5; i++) assert.throws(() => service.verify(third.challengeId, 'bad'));
  assert.throws(() => service.verify(third.challengeId, sent.code));
  const failing = createOtpService({ now: () => time, send: async () => { throw Error('private provider details'); } });
  await assert.rejects(failing.request(sent.phone), /could not be confirmed/);
  await assert.rejects(failing.request(sent.phone), /wait/);
  let complete;
  const concurrent = createOtpService({ send: () => new Promise(resolve => { complete = resolve; }) });
  const pending = concurrent.request(sent.phone);
  await assert.rejects(concurrent.request(sent.phone), /wait/);
  complete(); await pending;
  console.log('PASS: OTP expiry, replay protection, five attempts, resend cooldown, concurrent requests and safe failures; no SMS sent.');
})().catch(error => { console.error(error); process.exitCode = 1; });
